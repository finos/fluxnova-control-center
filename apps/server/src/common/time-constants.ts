export const ONE_DAY_IN_SEC = 60 * 60 * 24;
export const ONE_MONTH_IN_SEC = 60 * 60 * 24 * 30;
export const ONE_YEAR_IN_SEC = 60 * 60 * 24 * 365;

export const ONE_DAY_IN_MS = 1000 * ONE_DAY_IN_SEC;
export const ONE_MONTH_IN_MS = 1000 * ONE_MONTH_IN_SEC;
export const ONE_YEAR_IN_MS = 1000 * ONE_YEAR_IN_SEC;
